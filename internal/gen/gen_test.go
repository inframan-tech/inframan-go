func specOf(t *testing.T, caps ...Capability) []byte {
	t.Helper()
	raw, err := json.Marshal(Spec{SpecVersion: 1, Hash: "sha256:abc", BasePath: "/api", Capabilities: caps})
	if err != nil {
		t.Fatal(err)
	}
	return raw
}

