func generate(t *testing.T, caps ...Capability) string {
	t.Helper()
	out, err := Generate(specOf(t, caps...), Options{Source: "test.json"})
	if err != nil {
		t.Fatal(err)
	}
	return string(out)
}

func TestGenerateWritesATypedMethodPerCapability(t *testing.T) {
	src := generate(t, runAgent, listThings)
	for _, want := range []string{
		"// Code generated by inframan-gen from test.json; DO NOT EDIT.",
		`const SpecHash = "sha256:abc"`,
		"func (c *Client) RunAgent(ctx context.Context, p RunAgentParams) (json.RawMessage, error) {",
		`return c.invoke(ctx, "run_agent", p.args())`,
		"type RunAgentParams struct {",
		"ServiceID string `json:\"service_id\"`",
		"Input *string `json:\"input,omitempty\"`",
		"Mode *RunAgentMode `json:\"mode,omitempty\"`",
		"Limit *int `json:\"limit,omitempty\"`",
		"DryRun bool `json:\"dry_run\"`",
		"type RunAgentMode string",
		`RunAgentModeFast RunAgentMode = "fast"`,
		`RunAgentModeVerySlow RunAgentMode = "very-slow"`,
		`RunAgentModeV2x RunAgentMode = "2x"`,
		`RunAgentModeValue3 RunAgentMode = ""`,
		`a["service_id"] = p.ServiceID`,
		"if p.Mode != nil {\n\t\ta[\"mode\"] = string(*p.Mode)\n\t}",
		`a["dry_run"] = p.DryRun`,
		"func (c *Client) RunAgentPages(ctx context.Context, p RunAgentParams, page func(json.RawMessage) error) error {",
		"func (c *Client) ListThings(ctx context.Context, p ListThingsParams) (json.RawMessage, error) {",
		"type ListThingsParams struct {\n}",
		"func (p ListThingsParams) args() map[string]any {\n\treturn nil\n}",
		"// RunAgent calls run_agent: POST /v1/capabilities/agents/:service_id/runs.",
		"// A run is a Job.\n//\n// Read it with get_agent_run.",
		"// It needs the service:deploy permission, changes state and is offered to",
		"// Any signed-in caller may call it, changes nothing and is not offered to",
		`Name:       "run_agent",`,
		`{Name: "service_id", Type: "string", In: "path", Required: true},`,
		`{Name: "mode", Type: "string", In: "body", Enum: []string{"fast", "very-slow", "2x", ""}},`,
		"RegisterRoute(c.Name, c.Route())",
	} {
		if !strings.Contains(squash(src), squash(want)) {
			t.Errorf("the generated file lacks:\n%s", want)
		}
	}
	if strings.Contains(src, "ListThingsPages") {
		t.Error("a capability that takes no cursor was given a Pages helper")
	}
}

// squash is s with every run of spaces and tabs one space: gofmt aligns.
func squash(s string) string {
	var b strings.Builder
	space := false
	for _, r := range s {
		if r == ' ' || r == '\t' {
			if !space {
				b.WriteByte(' ')
			}
			space = true
			continue
		}
		space = false
		b.WriteRune(r)
	}
	return b.String()
}

func TestGenerateIsDeterministic(t *testing.T) {
	a := generate(t, runAgent, listThings)
	for i := 0; i < 5; i++ {
		if b := generate(t, runAgent, listThings); b != a {
			t.Fatal("the same spec generated two different files")
		}
	}
}

func TestTheGeneratedFileParses(t *testing.T) {
	src := generate(t, runAgent, listThings)
	f, err := parser.ParseFile(token.NewFileSet(), "zz.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	methods := 0
	for _, d := range f.Decls {
		if fn, ok := d.(*ast.FuncDecl); ok && fn.Recv != nil && fn.Doc != nil {
			methods++
		}
	}
	if methods != 3 { // RunAgent, RunAgentPages, ListThings
		t.Errorf("%d documented methods, want 3", methods)
	}
}

func TestDocCommentsAreWrapped(t *testing.T) {
	long := runAgent
	long.Description = strings.Repeat("word ", 60) + "\n  indented line that must not read as code"
	src := generate(t, long)
	for _, line := range strings.Split(src, "\n") {
		trimmed := strings.TrimLeft(line, "\t")
		if strings.HasPrefix(trimmed, "//") && len(trimmed) > 80 {
			t.Errorf("a comment line of %d characters: %q", len(trimmed), trimmed)
		}
		if strings.HasPrefix(trimmed, "//   indented") || strings.HasPrefix(trimmed, "//\tindented") {
			t.Errorf("an indented line became a code block: %q", trimmed)
		}
	}
}

func TestGenerateRefusesWhatItCannotName(t *testing.T) {
	dupParam := runAgent
	dupParam.Params = []Param{
		{Name: "app_id", Type: "string", In: "query", Description: "a"},
		{Name: "app__id", Type: "string", In: "query", Description: "b"},
	}
	call := listThings
	call.Name = "call"
	twoNames := listThings
	twoNames.Name = "list__things"
	badIn := listThings
	badIn.Params = []Param{{Name: "x", Type: "string", In: "header", Description: "x"}}
	badType := listThings
	badType.Params = []Param{{Name: "x", Type: "object", In: "body", Description: "x"}}
	for name, caps := range map[string][]Capability{
		"two parameters, one field":  {dupParam},
		"the Client's own method":    {call},
		"two capabilities, one name": {listThings, twoNames},
		"a parameter in a header":    {badIn},
		"an unknown type":            {badType},
		"listed twice":               {listThings, listThings},
	} {
		if _, err := Generate(specOf(t, caps...), Options{}); err == nil {
			t.Errorf("%s: generated, want a refusal", name)
		}
	}
	if _, err := Generate([]byte(`{"spec_version": 2, "capabilities": []}`), Options{}); err == nil ||
		!strings.Contains(err.Error(), "spec_version 2") {
		t.Errorf("a spec of another version: %v", err)
	}
}

